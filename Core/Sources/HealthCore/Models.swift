import Foundation

/// All values are derived from HealthKit records or from explicit user input.
/// No synthetic measurement data is shipped with the app.
public struct MetricReading: Codable, Identifiable, Equatable, Sendable {
    public let id: String
    public let value: Double
    public let unit: String
    public let recordedAt: Date
    public let source: String

    public init(id: String, value: Double, unit: String, recordedAt: Date, source: String) {
        self.id = id
        self.value = value
        self.unit = unit
        self.recordedAt = recordedAt
        self.source = source
    }
}

public struct TrendPoint: Codable, Identifiable, Equatable, Sendable {
    public var id: Date { recordedAt }
    public let recordedAt: Date
    public let value: Double

    public init(recordedAt: Date, value: Double) {
        self.recordedAt = recordedAt
        self.value = value
    }
}

public enum SleepStage: String, Codable, CaseIterable, Sendable {
    case rem = "REM"
    case core = "核心"
    case deep = "深睡"
    case unspecified = "其他睡眠"
    case awake = "清醒"
}

public struct SleepInterval: Codable, Equatable, Sendable {
    public let start: Date
    public let end: Date
    public let stage: SleepStage

    public init(start: Date, end: Date, stage: SleepStage) {
        self.start = start
        self.end = end
        self.stage = stage
    }
}

public struct SleepSummary: Codable, Equatable, Sendable {
    public var minutesByStage: [SleepStage: Int]
    public var totalAsleepMinutes: Int
    public var minutesAwake: Int

    public init(minutesByStage: [SleepStage: Int], totalAsleepMinutes: Int, minutesAwake: Int) {
        self.minutesByStage = minutesByStage
        self.totalAsleepMinutes = totalAsleepMinutes
        self.minutesAwake = minutesAwake
    }
}

public struct ECGSummary: Codable, Identifiable, Sendable {
    public let id: UUID
    public let recordedAt: Date
    public let classification: String
    public let averageHeartRate: Double?
    public let source: String?

    public init(id: UUID, recordedAt: Date, classification: String, averageHeartRate: Double?, source: String? = nil) {
        self.id = id
        self.recordedAt = recordedAt
        self.classification = classification
        self.averageHeartRate = averageHeartRate
        self.source = source
    }
}

public struct JournalEntry: Codable, Identifiable, Sendable {
    public let id: UUID
    public var timestamp: Date
    public var category: Category
    public var title: String
    public var detail: String

    public enum Category: String, Codable, CaseIterable, Sendable {
        case symptom = "症状"
        case medication = "用药"
        case note = "健康笔记"
    }

    public init(id: UUID = UUID(), timestamp: Date = Date(), category: Category, title: String, detail: String) {
        self.id = id
        self.timestamp = timestamp
        self.category = category
        self.title = title
        self.detail = detail
    }
}

public struct HealthInsight: Identifiable, Equatable, Sendable {
    public let id: String
    public let title: String
    public let body: String
    public let supportingMetricIDs: [String]

    public init(id: String, title: String, body: String, supportingMetricIDs: [String]) {
        self.id = id
        self.title = title
        self.body = body
        self.supportingMetricIDs = supportingMetricIDs
    }
}


/// A system-generated alert recorded by HealthKit, not an alert generated by this app.
public struct HeartEvent: Identifiable, Codable, Equatable, Sendable {
    public let id: UUID
    public let type: String
    public let date: Date
    public let source: String
    public init(id: UUID, type: String, date: Date, source: String) {
        self.id = id; self.type = type; self.date = date; self.source = source
    }
}

/// Voltage points from a previously recorded Apple Watch ECG. Never generated by the app.
public struct ECGVoltagePoint: Identifiable, Equatable, Sendable {
    public var id: Double { seconds }
    public let seconds: Double
    public let millivolts: Double
    public init(seconds: Double, millivolts: Double) { self.seconds = seconds; self.millivolts = millivolts }
}
